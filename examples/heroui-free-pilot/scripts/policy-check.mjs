import { readFileSync, readdirSync } from "node:fs";
import assert from "node:assert/strict";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "..");
const pkg = JSON.parse(readFileSync(path.join(root,"package.json"),"utf8"));
const source = readFileSync(path.join(root,"src/App.jsx"),"utf8");
const css = readFileSync(path.join(root,"src/styles.css"),"utf8");
assert.equal(pkg.dependencies["@heroui/react"],"3.2.6");
assert.equal(pkg.dependencies["@heroui/styles"],"3.2.6");
assert.ok(Number(pkg.dependencies.react.split(".")[0])>=19,"React 19 required");
assert.ok(Number(pkg.devDependencies.tailwindcss.split(".")[0])>=4,"Tailwind v4 required");
assert.ok(source.includes('from "@heroui/react"') && source.includes("<Button"),"Real free component render required");
assert.ok(css.indexOf('@import "tailwindcss"') < css.indexOf('@import "@heroui/styles"'),"CSS import order");
assert.ok(!source.includes("HeroUIProvider"),"Reject obsolete HeroUI v2 API");
assert.ok(!source.toLowerCase().includes("heroui pro"),"Reject Pro code");
assert.ok(source.includes("INTERNAL / SYNTHETIC") && source.includes("No backend or analytics"),"Demonstration claims must be honest");
assert.ok(css.includes("prefers-reduced-motion"),"Reduced motion required");
assert.ok(readdirSync(path.join(root,"tests")).length>0,"Real browser tests required");
console.log("HeroUI free-policy contracts: 10/10 PASS. No production/runtime claim.");
